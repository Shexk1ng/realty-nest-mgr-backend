const DOPUSZCZALNE_SKALE: Readonly<Record<Skala, readonly Skala[]>> = {
  MALY: ["MALY", "SREDNI"],
  SREDNI: ["SREDNI", "MALY", "DUZY"],
  DUZY: ["DUZY", "SREDNI"],
};

export function zdjeciaDla(
  kategoria: KategoriaZdjecia,
  ujecie: Ujecie | null = null,
  skala: Skala | null = null,
  parcela: readonly CharakterParceli[] | null = null,
): readonly Zdjecie[] {
  return ZDJECIA.filter((z) => {
    if (z.kategoria !== kategoria) return false;
    if (ujecie !== null && z.ujecie !== ujecie) return false;
    if (skala !== null && z.skala !== null && z.skala !== skala) return false;
    if (parcela !== null && (z.parcela === null || !parcela.includes(z.parcela)))
      return false;
    return true;
  });
}

function losowy(ziarno: number): () => number {
  let stan = (ziarno * 2_654_435_761) % 2_147_483_647;
  if (stan <= 0) stan += 2_147_483_646;
  return () => {
    stan = (stan * 16_807) % 2_147_483_647;
    return (stan - 1) / 2_147_483_646;
  };
}

export interface ParametryGalerii {
  readonly kategoria: KategoriaZdjecia;
  readonly metraz: number | null;
  readonly ile: number;
  readonly ziarno: number;
  readonly parcela?: readonly CharakterParceli[];
}

export function zbudujGalerie(p: ParametryGalerii): readonly string[] {
  const skala = p.metraz === null ? null : skalaDlaMetrazu(p.metraz);
  const kolejnosc = KOLEJNOSC_UJEC[p.kategoria];
  const rand = losowy(p.ziarno);
  const parcela = p.parcela ?? null;

  const potasuj = (lista: Zdjecie[]): Zdjecie[] => {
    for (let i = lista.length - 1; i > 0; i -= 1) {
      const j = Math.floor(rand() * (i + 1));
      const a = lista[i];
      const b = lista[j];
      if (a !== undefined && b !== undefined) {
        lista[i] = b;
        lista[j] = a;
      }
    }
    return lista;
  };

  const pule: Zdjecie[][] = kolejnosc.map((ujecie) => {
    const wszystkie = zdjeciaDla(p.kategoria, ujecie, null, parcela);
    if (skala === null) return potasuj([...wszystkie]);
    const warstwy = DOPUSZCZALNE_SKALE[skala].flatMap((s) => {
      const warstwa = wszystkie.filter((z) => z.skala === s);
      return warstwa.length > 0 ? [potasuj(warstwa)] : [];
    });
    const bezSkali = wszystkie.filter((z) => z.skala === null);
    if (bezSkali.length > 0) warstwy.push(potasuj(bezSkali));
    const pula = warstwy.flat();
    return pula.length > 0 ? pula : potasuj([...wszystkie]);
  });

  const wybrane: string[] = [];
  const uzyte = new Set<string>();
  let runda = 0;
  while (wybrane.length < p.ile && runda < 16) {
    let dodano = false;
    for (const pula of pule) {
      if (wybrane.length >= p.ile) break;
      const kandydat = pula[runda];
      if (kandydat === undefined || uzyte.has(kandydat.url)) continue;
      uzyte.add(kandydat.url);
      wybrane.push(kandydat.url);
      dodano = true;
    }
    if (!dodano) break;
    runda += 1;
  }
  return wybrane;
}

