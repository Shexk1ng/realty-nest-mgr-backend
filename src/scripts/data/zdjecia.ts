export const miniatura = (url: string): string => {
  const [baza = url] = url.split("?");
  return baza.includes("images.unsplash.com")
    ? `${baza}?w=400&fit=crop&auto=format&q=70`
    : `${baza}?auto=compress&cs=tinysrgb&w=400`;
};

